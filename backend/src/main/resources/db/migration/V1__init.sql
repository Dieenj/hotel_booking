-- Baseline schema: identical to what Hibernate (ddl-auto: update) created before Flyway was
-- introduced, including constraint names, so existing databases can be baselined at V1.
-- Kept to SQL that runs on both PostgreSQL and H2 (tests).

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    active      BOOLEAN      NOT NULL,
    email       VARCHAR(255) NOT NULL,
    full_name   VARCHAR(255) NOT NULL,
    password    VARCHAR(255) NOT NULL,
    phone       VARCHAR(255),
    role        VARCHAR(255) NOT NULL,
    CONSTRAINT users_role_check CHECK (role IN ('GUEST', 'ADMIN')),
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email)
);

CREATE TABLE hotels (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP(6),
    updated_at   TIMESTAMP(6),
    active       BOOLEAN      NOT NULL,
    address      VARCHAR(255) NOT NULL,
    city         VARCHAR(255) NOT NULL,
    country      VARCHAR(255),
    description  TEXT,
    name         VARCHAR(255) NOT NULL,
    star_rating  INTEGER
);

CREATE TABLE hotel_amenities (
    hotel_id  BIGINT NOT NULL,
    amenity   VARCHAR(255),
    CONSTRAINT fk5v984hm7iyuvyccsgboplo7ii FOREIGN KEY (hotel_id) REFERENCES hotels (id)
);

CREATE TABLE hotel_images (
    hotel_id   BIGINT NOT NULL,
    image_url  VARCHAR(255),
    CONSTRAINT fkrj3n45f8oqy1yr996g14j757i FOREIGN KEY (hotel_id) REFERENCES hotels (id)
);

CREATE TABLE room_types (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6),
    updated_at    TIMESTAMP(6),
    active        BOOLEAN          NOT NULL,
    area          DOUBLE PRECISION,
    base_price    NUMERIC(15, 2)   NOT NULL,
    description   TEXT,
    max_capacity  INTEGER,
    name          VARCHAR(255)     NOT NULL,
    total_rooms   INTEGER          NOT NULL,
    hotel_id      BIGINT           NOT NULL,
    CONSTRAINT fk42cc0t2sr43om89u1loqh7arj FOREIGN KEY (hotel_id) REFERENCES hotels (id)
);

CREATE TABLE room_type_amenities (
    room_type_id  BIGINT NOT NULL,
    amenity       VARCHAR(255),
    CONSTRAINT fkdo00a57krcy83usnwd9xclxhk FOREIGN KEY (room_type_id) REFERENCES room_types (id)
);

CREATE TABLE room_type_images (
    room_type_id  BIGINT NOT NULL,
    image_url     VARCHAR(255),
    CONSTRAINT fkmw5uodvci9hlcamwwkxg7mhvk FOREIGN KEY (room_type_id) REFERENCES room_types (id)
);

CREATE TABLE room_inventory (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    available_rooms  INTEGER NOT NULL,
    booked_rooms     INTEGER NOT NULL,
    date             DATE    NOT NULL,
    total_rooms      INTEGER NOT NULL,
    room_type_id     BIGINT  NOT NULL,
    CONSTRAINT ukh5d3ghe5njf5r5tajjhrukhm9 UNIQUE (room_type_id, date),
    CONSTRAINT fk2gfxdmx30uknhd71yypxpqa8f FOREIGN KEY (room_type_id) REFERENCES room_types (id)
);

CREATE TABLE bookings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       TIMESTAMP(6),
    updated_at       TIMESTAMP(6),
    booking_code     VARCHAR(255)   NOT NULL,
    check_in         DATE           NOT NULL,
    check_out        DATE           NOT NULL,
    guest_email      VARCHAR(255)   NOT NULL,
    guest_name       VARCHAR(255)   NOT NULL,
    guest_phone      VARCHAR(255),
    guests           INTEGER        NOT NULL,
    special_request  TEXT,
    status           VARCHAR(255)   NOT NULL,
    total_price      NUMERIC(15, 2) NOT NULL,
    room_type_id     BIGINT         NOT NULL,
    user_id          BIGINT         NOT NULL,
    CONSTRAINT bookings_status_check
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CHECKED_IN', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ukq97166k18hklq6ls46osbrftx UNIQUE (booking_code),
    CONSTRAINT fkgxj821at0er9dtw7wtyc05ni1 FOREIGN KEY (room_type_id) REFERENCES room_types (id),
    CONSTRAINT fkeyog2oic85xg7hsu2je2lx3s6 FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE reviews (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMP(6),
    updated_at          TIMESTAMP(6),
    cleanliness_rating  INTEGER,
    comment             TEXT,
    location_rating     INTEGER,
    rating              INTEGER NOT NULL,
    service_rating      INTEGER,
    value_rating        INTEGER,
    booking_id          BIGINT  NOT NULL,
    hotel_id            BIGINT  NOT NULL,
    user_id             BIGINT  NOT NULL,
    CONSTRAINT uk3p9j9vyr1qofbcxju65es206r UNIQUE (booking_id),
    CONSTRAINT fk28an517hrxtt2bsg93uefugrm FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT fkb9igk5exfb4knqklcvka6cdhx FOREIGN KEY (hotel_id) REFERENCES hotels (id),
    CONSTRAINT fkcgy7qjc1r99dp117y9en6lxye FOREIGN KEY (user_id) REFERENCES users (id)
);
